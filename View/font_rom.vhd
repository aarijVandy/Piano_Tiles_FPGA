-- font_rom.vhd
-- Read-only bitmap font for the display pipeline.
-- Each character occupies a 5x7 pixel area centred in an 8x8 cell.
--
-- Encoding (6-bit char_code input):
--   0-9  : digit glyphs
--  10-35 : uppercase A-Z  (unused letters output a blank glyph)
--  36    : colon ':'
--  37    : equals '='
--  other : blank (pixel = '0')
--
-- Bit convention for each row byte (7 downto 0):
--   bit 7 = leftmost pixel column 0
--   bit 6 = column 1  (first used column)
--   bit 5 = column 2
--   bit 4 = column 3  (centre)
--   bit 3 = column 4
--   bit 2 = column 5  (last used column)
--   bit 1 = column 6  (padding)
--   bit 0 = column 7  (padding)
-- Character content spans columns 1-5 (5 pixels wide), row 7 is always blank.

LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;

ENTITY font_rom IS
	PORT (
		char_code : IN  STD_LOGIC_VECTOR(5 DOWNTO 0); -- character index (see encoding above)
		row       : IN  STD_LOGIC_VECTOR(2 DOWNTO 0); -- pixel row within character (0-7)
		col       : IN  STD_LOGIC_VECTOR(2 DOWNTO 0); -- pixel column within character (0-7)
		pixel     : OUT STD_LOGIC
	);
END ENTITY;

ARCHITECTURE rtl OF font_rom IS

	-- 38 characters (0-37), each 8 rows of 8 bits.
	TYPE font_array IS ARRAY (0 TO 37, 0 TO 7) OF STD_LOGIC_VECTOR(7 DOWNTO 0);

	-- Helper notation (columns 1-5 active, bit6=col1 ... bit2=col5):
	--   #.... = 0x40   .###. = 0x38   ##### = 0x7C   ####. = 0x78
	--   #...# = 0x44   ..#.. = 0x10   #.#.# = 0x54   .#.#. = 0x28
	CONSTANT glyph_rom : font_array := (

		-- ---- Digits 0-9 (unchanged) ----------------------------------------

		-- 0: .###. / #...# / #...# / #...# / #...# / #...# / .###. / .....
		0 => ("00111000","01000100","01000100","01000100","01000100","01000100","00111000","00000000"),
		-- 1: ..#.. / .##.. / ..#.. / ..#.. / ..#.. / ..#.. / .###. / .....
		1 => ("00010000","00110000","00010000","00010000","00010000","00010000","00111000","00000000"),
		-- 2: .###. / #...# / ....# / ...#. / ..#.. / .#... / ##### / .....
		2 => ("00111000","01000100","00000100","00001000","00010000","00100000","01111100","00000000"),
		-- 3: .###. / #...# / ....# / .###. / ....# / #...# / .###. / .....
		3 => ("00111000","01000100","00000100","00011000","00000100","01000100","00111000","00000000"),
		-- 4: ....# / ...## / ..#.# / .#..# / ##### / ....# / ....# / .....
		4 => ("00001000","00011000","00101000","01001000","01111100","00001000","00001000","00000000"),
		-- 5: ##### / #.... / ####. / ....# / ....# / #...# / .###. / .....
		5 => ("01111100","01000000","01111000","00000100","00000100","01000100","00111000","00000000"),
		-- 6: .###. / #...# / #.... / ####. / #...# / #...# / .###. / .....
		6 => ("00111000","01000100","01000000","01111000","01000100","01000100","00111000","00000000"),
		-- 7: ##### / ....# / ...#. / ..#.. / .#... / .#... / .#... / .....
		7 => ("01111100","00000100","00001000","00010000","00100000","00100000","00100000","00000000"),
		-- 8: .###. / #...# / #...# / .###. / #...# / #...# / .###. / .....
		8 => ("00111000","01000100","01000100","00111000","01000100","01000100","00111000","00000000"),
		-- 9: .###. / #...# / #...# / .####/ ....# / #...# / .###. / .....
		9 => ("00111000","01000100","01000100","00111100","00000100","01000100","00111000","00000000"),

		-- ---- Uppercase A-Z (indices 10-35) ----------------------------------

		-- A (10): .###. / #...# / #...# / ##### / #...# / #...# / #...# / .....
		10 => ("00111000","01000100","01000100","01111100","01000100","01000100","01000100","00000000"),
		-- B (11): ####. / #...# / #...# / ####. / #...# / #...# / ####. / .....
		11 => ("01111000","01000100","01000100","01111000","01000100","01000100","01111000","00000000"),
		-- C (12): .###. / #...# / #.... / #.... / #.... / #...# / .###. / .....
		12 => ("00111000","01000100","01000000","01000000","01000000","01000100","00111000","00000000"),
		-- D (13): (not needed -- blank glyph)
		13 => ("00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"),
		-- E (14): ##### / #.... / #.... / ####. / #.... / #.... / ##### / .....
		14 => ("01111100","01000000","01000000","01111000","01000000","01000000","01111100","00000000"),
		-- F (15): (not needed -- blank glyph)
		15 => ("00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"),
		-- G (16): .###. / #.... / #.... / #.##. / #...# / #...# / .###. / .....
		-- #.##. = col1,col3,col4 = bit6+bit4+bit3 = 0x58
		16 => ("00111000","01000000","01000000","01011000","01000100","01000100","00111000","00000000"),
		-- H (17): #...# / #...# / #...# / ##### / #...# / #...# / #...# / .....
		17 => ("01000100","01000100","01000100","01111100","01000100","01000100","01000100","00000000"),
		-- I (18): .###. / ..#.. / ..#.. / ..#.. / ..#.. / ..#.. / .###. / .....
		18 => ("00111000","00010000","00010000","00010000","00010000","00010000","00111000","00000000"),
		-- J (19): (not needed -- blank glyph)
		19 => ("00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"),
		-- K (20): #...# / #..#. / #.#.. / ##... / #.#.. / #..#. / #...# / .....
		-- ##... = col1,col2 = bit6+bit5 = 0x60
		-- #.#.. = col1,col3 = bit6+bit4 = 0x50
		-- #..#. = col1,col4 = bit6+bit3 = 0x48
		20 => ("01000100","01001000","01010000","01100000","01010000","01001000","01000100","00000000"),
		-- L (21): #.... / #.... / #.... / #.... / #.... / #.... / ##### / .....
		21 => ("01000000","01000000","01000000","01000000","01000000","01000000","01111100","00000000"),
		-- M (22): #...# / ##.## / #.#.# / #...# / #...# / #...# / #...# / .....
		-- ##.## = col1,col2,col4,col5 = bit6+bit5+bit3+bit2 = 0x6C
		-- #.#.# = col1,col3,col5 = bit6+bit4+bit2 = 0x54
		22 => ("01000100","01101100","01010100","01000100","01000100","01000100","01000100","00000000"),
		-- N (23): #...# / ##..# / #.#.# / #..## / #...# / #...# / #...# / .....
		-- ##..# = col1,col2,col5 = bit6+bit5+bit2 = 0x64
		-- #..## = col1,col4,col5 = bit6+bit3+bit2 = 0x4C
		23 => ("01000100","01100100","01010100","01001100","01000100","01000100","01000100","00000000"),
		-- O (24): .###. / #...# / #...# / #...# / #...# / #...# / .###. / .....
		24 => ("00111000","01000100","01000100","01000100","01000100","01000100","00111000","00000000"),
		-- P (25): ####. / #...# / #...# / ####. / #.... / #.... / #.... / .....
		25 => ("01111000","01000100","01000100","01111000","01000000","01000000","01000000","00000000"),
		-- Q (26): (not needed -- blank glyph)
		26 => ("00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"),
		-- R (27): ####. / #...# / #...# / ####. / #.#.. / #..#. / #...# / .....
		27 => ("01111000","01000100","01000100","01111000","01010000","01001000","01000100","00000000"),
		-- S (28): .###. / #...# / #.... / .###. / ....# / #...# / .###. / .....
		28 => ("00111000","01000100","01000000","00111000","00000100","01000100","00111000","00000000"),
		-- T (29): ##### / ..#.. / ..#.. / ..#.. / ..#.. / ..#.. / ..#.. / .....
		29 => ("01111100","00010000","00010000","00010000","00010000","00010000","00010000","00000000"),
		-- U (30): #...# / #...# / #...# / #...# / #...# / #...# / .###. / .....
		30 => ("01000100","01000100","01000100","01000100","01000100","01000100","00111000","00000000"),
		-- V (31): #...# / #...# / #...# / #...# / .#.#. / .#.#. / ..#.. / .....
		-- .#.#. = col2,col4 = bit5+bit3 = 0x28
		31 => ("01000100","01000100","01000100","01000100","00101000","00101000","00010000","00000000"),
		-- W (32): #...# / #...# / #.#.# / #.#.# / ##.## / ##.## / #...# / .....
		32 => ("01000100","01000100","01010100","01010100","01101100","01101100","01000100","00000000"),
		-- X (33): #...# / #...# / .#.#. / ..#.. / .#.#. / #...# / #...# / .....
		33 => ("01000100","01000100","00101000","00010000","00101000","01000100","01000100","00000000"),
		-- Y (34): #...# / #...# / .#.#. / ..#.. / ..#.. / ..#.. / ..#.. / .....
		34 => ("01000100","01000100","00101000","00010000","00010000","00010000","00010000","00000000"),
		-- Z (35): (not needed -- blank glyph)
		35 => ("00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"),

		-- ---- Punctuation (indices 36-37) ------------------------------------

		-- Colon ':' (36): ..... / ..#.. / ..#.. / ..... / ..#.. / ..#.. / ..... / .....
		36 => ("00000000","00010000","00010000","00000000","00010000","00010000","00000000","00000000"),
		-- Equals '=' (37): ..... / ..... / ##### / ..... / ##### / ..... / ..... / .....
		37 => ("00000000","00000000","01111100","00000000","01111100","00000000","00000000","00000000")
	);

BEGIN
	PROCESS (char_code, row, col)
		VARIABLE d_idx : INTEGER RANGE 0 TO 63;
		VARIABLE r_idx : INTEGER RANGE 0 TO 7;
		VARIABLE c_idx : INTEGER RANGE 0 TO 7;
	BEGIN
		d_idx := to_integer(unsigned(char_code));
		r_idx := to_integer(unsigned(row));
		c_idx := to_integer(unsigned(col));

		-- Output the pixel bit for valid character codes; blank for everything else.
		IF d_idx >= 0 AND d_idx <= 37 THEN
			-- bit 7 is leftmost (col 0); c_idx=0 selects bit 7, etc.
			pixel <= glyph_rom(d_idx, r_idx)(7 - c_idx);
		ELSE
			pixel <= '0';
		END IF;
	END PROCESS;
END ARCHITECTURE;
